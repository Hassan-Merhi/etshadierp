import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONFIG_PATH = path.join(ROOT, "config", "legacy-route-boundaries.json");
const DEFAULT_JSON_PATH = path.join(ROOT, "artifacts", "legacy-route-inventory.json");
const DEFAULT_MARKDOWN_PATH = path.join(ROOT, "docs", "engineering", "legacy-route-inventory.md");
const HTTP_METHODS = new Set(["get", "post", "put", "patch", "delete", "options", "head", "all", "use"]);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function lineCount(source) {
  if (source.length === 0) return 0;
  return source.split(/\r?\n/).length;
}

function lineNumberAt(source, index) {
  return source.slice(0, index).split(/\r?\n/).length;
}

function normalizePathExpression(value) {
  return value.replace(/\s+/g, " ").trim();
}

function extractRouteRegistrations(source, filePath) {
  const registrations = [];
  const routeRegex = /\b(?:app|router)\s*\.\s*(get|post|put|patch|delete|options|head|all|use)\s*\(\s*([`'\"])([\s\S]*?)\2/g;
  let match;

  while ((match = routeRegex.exec(source)) !== null) {
    const method = match[1].toLowerCase();
    if (!HTTP_METHODS.has(method)) continue;

    const routePath = normalizePathExpression(match[3]);
    registrations.push({
      file: filePath,
      line: lineNumberAt(source, match.index),
      method: method.toUpperCase(),
      path: routePath,
      signature: `${method.toUpperCase()} ${routePath}`,
    });
  }

  return registrations;
}

function findDuplicates(registrations) {
  const grouped = new Map();
  for (const registration of registrations) {
    const entries = grouped.get(registration.signature) ?? [];
    entries.push(registration);
    grouped.set(registration.signature, entries);
  }

  return [...grouped.entries()]
    .filter(([, entries]) => entries.length > 1)
    .map(([signature, entries]) => ({ signature, entries }));
}

export function auditLegacyRouteBoundaries({ root = ROOT } = {}) {
  const configPath = path.join(root, path.relative(ROOT, CONFIG_PATH));
  const config = readJson(configPath);
  const files = [];
  const allRegistrations = [];
  const failures = [];

  for (const boundary of config.files) {
    const absolutePath = path.join(root, boundary.path);
    if (!fs.existsSync(absolutePath)) {
      failures.push(`${boundary.path} is missing; remove it from the baseline only when its routes are fully migrated.`);
      continue;
    }

    const source = fs.readFileSync(absolutePath, "utf8");
    const actualLines = lineCount(source);
    const registrations = extractRouteRegistrations(source, boundary.path);
    allRegistrations.push(...registrations);

    if (actualLines > boundary.maxLines) {
      failures.push(`${boundary.path} grew to ${actualLines} lines; frozen maximum is ${boundary.maxLines}.`);
    }

    files.push({
      ...boundary,
      actualLines,
      remainingToTarget: Math.max(0, actualLines - boundary.targetLines),
      routeRegistrations: registrations.length,
      routes: registrations,
    });
  }

  const duplicateRoutes = findDuplicates(allRegistrations);
  return {
    generatedAt: new Date().toISOString(),
    configVersion: config.version,
    summary: {
      legacyFiles: files.length,
      totalLines: files.reduce((sum, file) => sum + file.actualLines, 0),
      totalRouteRegistrations: allRegistrations.length,
      duplicateRouteSignatures: duplicateRoutes.length,
      failures: failures.length,
    },
    files,
    duplicateRoutes,
    failures,
  };
}

function toMarkdown(report) {
  const lines = [
    "# Legacy Route Inventory",
    "",
    "> Generated by `node scripts/audit-legacy-route-boundaries.mjs --write`.",
    "",
    `- Legacy files: ${report.summary.legacyFiles}`,
    `- Total lines: ${report.summary.totalLines}`,
    `- Route registrations: ${report.summary.totalRouteRegistrations}`,
    `- Duplicate route signatures inside legacy registries: ${report.summary.duplicateRouteSignatures}`,
    "",
    "## Reduction Baseline",
    "",
    "| File | Owner | Current lines | Frozen maximum | Target | Phase | Routes |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
  ];

  for (const file of report.files) {
    lines.push(`| \`${file.path}\` | ${file.owner} | ${file.actualLines} | ${file.maxLines} | ${file.targetLines} | ${file.migrationPhase} | ${file.routeRegistrations} |`);
  }

  for (const file of report.files) {
    lines.push("", `## ${file.path}`, "", `Owner: **${file.owner}**`, "", "| Method | Path | Line |", "| --- | --- | ---: |");
    if (file.routes.length === 0) {
      lines.push("| — | No literal route registrations detected | — |");
    } else {
      for (const route of file.routes) {
        lines.push(`| ${route.method} | \`${route.path.replace(/\|/g, "\\|")}\` | ${route.line} |`);
      }
    }
  }

  lines.push("", "## Duplicate Signatures", "");
  if (report.duplicateRoutes.length === 0) {
    lines.push("No duplicate literal route signatures were detected inside the four legacy registries.");
  } else {
    for (const duplicate of report.duplicateRoutes) {
      lines.push(`- \`${duplicate.signature}\`: ${duplicate.entries.map((entry) => `${entry.file}:${entry.line}`).join(", ")}`);
    }
  }

  lines.push("", "## Rules", "", "1. The frozen maximum for a legacy file may never increase.", "2. New endpoints belong in focused domain route modules, not these compatibility registries.", "3. When routes migrate, lower the matching `maxLines` value in `config/legacy-route-boundaries.json` in the same change.", "4. Delete a legacy file from the baseline only after its final route has moved and the compatibility registration is removed.", "");
  return lines.join("\n");
}

function writeReport(report, jsonPath = DEFAULT_JSON_PATH, markdownPath = DEFAULT_MARKDOWN_PATH) {
  fs.mkdirSync(path.dirname(jsonPath), { recursive: true });
  fs.mkdirSync(path.dirname(markdownPath), { recursive: true });
  fs.writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`);
  fs.writeFileSync(markdownPath, toMarkdown(report));
}

function main() {
  const args = new Set(process.argv.slice(2));
  const report = auditLegacyRouteBoundaries();

  if (args.has("--write")) {
    writeReport(report);
  }

  console.log(JSON.stringify(report.summary, null, 2));
  if (report.duplicateRoutes.length > 0) {
    console.warn(`Found ${report.duplicateRoutes.length} duplicate legacy route signature(s); review the generated inventory.`);
  }

  if (report.failures.length > 0) {
    for (const failure of report.failures) console.error(`ERROR: ${failure}`);
    process.exitCode = 1;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
